ZH=dict(line.split('|',1) for line in DATA.splitlines())
PREFIXES=['ASP JavaScript','ASP Python','ASP VBScript','ASP X-Code','JavaScript','Python','PHP','HTML','SGML','VBScript']
POSITIONS={
 'down one line':'向下一行','down one page':'向下一页','down one paragraph':'向下一段',
 'up one line':'向上一行','up one page':'向上一页','up one paragraph':'向上一段',
 'left one character':'向左一个字符','left one word':'向左一个单词','left one word part':'向左一个单词片段',
 'right one character':'向右一个字符','right one word':'向右一个单词','right one word part':'向右一个单词片段',
 'to end of line':'到行尾','to end of displayed line':'到显示行行尾','to end of text':'到文本末尾',
 'to first visible character in line':'到本行首个可见字符','to start of line':'到行首',
 'to start of displayed line':'到显示行行首','to start of text':'到文本开头'}
def translate(source):
    if source in ZH:return ZH[source]
    for lead,zh in [('Extend rectangular selection ','扩展矩形选区'),('Extend selection ','扩展选区'),('Move ','移动')]:
        if source.startswith(lead):return zh+POSITIONS[source[len(lead):]]
    if source.startswith('User defined '):return '用户定义 '+source[len('User defined '):]
    for prefix in PREFIXES:
        if source.startswith(prefix+' '):
            tail=source[len(prefix)+1:]
            suffix=next((v for k,v in ZH.items() if k.lower()==tail.lower()),None)
            if suffix is not None:return prefix+' '+suffix
    raise ValueError('Missing Chinese label: '+source)
